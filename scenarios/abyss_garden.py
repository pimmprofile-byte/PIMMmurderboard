def pod_result(votes: dict) -> dict:
    """탈출 포드 개방 — 자기 자신은 못 찍는다.

    최다득표가 두 자리 안이면 그들이 탄다. 넷 이상이 동률이면 자리를 나눌 수 없어 아무도 못 탄다.
    한 명이면 혼자 나간다. 표를 흩뜨리는 것 자체가 무기가 되는 구조다.
    """
    tally: dict = {}
    for voter, target in (votes or {}).items():
        if not target or target == voter:
            continue
        tally[target] = tally.get(target, 0) + 1
    if not tally:
        return {"boarded": [], "tally": {}, "reason": "none", "top": 0}
    top = max(tally.values())
    leaders = sorted([k for k, v in tally.items() if v == top])
    if len(leaders) > POD_SEATS:
        return {"boarded": [], "tally": tally, "reason": "tie", "top": top}
    return {"boarded": leaders, "tally": tally, "reason": "solo" if len(leaders) == 1 else "seats", "top": top}


def arrest_needed(human_n: int, culprit_is_human: bool) -> int:
    """범인 검거에 필요한 지목 수. AI 표는 세지 않는다 — 판단은 사람 몫이다.

    범인이 사람 쪽에 있으면 범인을 포함한 인원의 과반(2인 1명, 3인 2명, 4인 2명).
    범인이 AI 쪽이면 사람 전체의 과반이되 반은 무조건 넘겨야 한다(2인 2명, 4인 3명).
    """
    n = max(1, int(human_n))
    return (n + 1) // 2 if culprit_is_human else (n // 2) + 1


def arrest_result(accuse: dict, human_ids: list, culprit_is_human: bool) -> dict:
    """accuse: roleId -> 지목한 roleId (사람만). 범인 본인의 표는 세지 않는다."""
    humans = [r for r in (human_ids or [])]
    need = arrest_needed(len(humans), culprit_is_human)
    hits = [r for r in humans if r != CULPRIT_ID and (accuse or {}).get(r) == CULPRIT_ID]
    return {"caught": len(hits) >= need, "hits": len(hits), "need": need,
            "voters": len(humans), "by": hits}


def compute_ending(grades: dict) -> dict | None:
    graded = [c["id"] for c in CHARACTERS]
    if not all(rid in grades for rid in graded):
        return None  # 아직 채점이 끝나지 않음 — 엔딩은 준비되지 않았다

    innocents = [rid for rid in graded if rid != CULPRIT_ID]
    guesses = {rid: (grades.get(rid, {}).get("culpritGuess") or "unknown") for rid in innocents}
    correct_votes = sum(1 for rid in innocents if guesses[rid] == CULPRIT_ID)
    # 오세린은 처음부터 범인을 알고 있었으므로 '추리로 도달했는가'에서 제외한다.
    deducers = [rid for rid in innocents if rid != "oserin"]
    exposed = sum(1 for rid in deducers if guesses[rid] == CULPRIT_ID) >= 2  # 넷 중 둘 이상

    # 진실을 수면 위로 올릴지 — 전원의 선택을 다수결로
    choices = [(grades.get(rid, {}).get("surface") or "gray") for rid in graded]
    tally = Counter(choices)
    top_n = max(tally.values())
    leaders = [k for k, v in tally.items() if v == top_n]
    consensus = leaders[0] if len(leaders) == 1 else "gray"

    if exposed and consensus == "surface":
        key = "surface"     # ① 문서까지 건져 올렸다 — 형의 이름도 함께 떠오른다
    elif exposed:
        key = "atone"       # ③ 그는 드러났지만 문서는 덮기로 — 그는 남는다
    elif consensus != "surface":
        key = "sunk"        # ② 아무도 도달하지 못했고 문서도 묻혔다 — 그가 이긴 밤
    else:
        key = "gray"        # ④ 절반만 떠오른 것

    e = ENDINGS[key]
    return {"key": key, "name": e["name"], "tone": e["tone"], "desc": e["desc"], "truth": TRUTH_FULL,
            "culpritId": CULPRIT_ID, "correctVotes": correct_votes, "guesses": guesses,
            "consensus": consensus, "exposed": exposed}


