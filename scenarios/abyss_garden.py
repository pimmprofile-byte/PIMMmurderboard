def keep_goal_result(role_id: str, hand: list, revealed: list) -> dict | None:
    """종막 시점에 '끝까지 쥐기' 목표가 달성됐는지 판정한다."""
    g = KEEP_GOALS.get(role_id)
    if not g:
        return None
    held = [c for c in g["cards"] if c in (hand or [])]
    lost = [c for c in g["cards"] if c in (revealed or [])]
    ok = len(held) == len(g["cards"])
    return {"roleId": role_id, "ok": ok, "points": g["points"] if ok else 0,
            "label": g["label"], "detail": ("끝까지 지켜냈다" if ok else (g["fail"] if lost else "끝내 손에 넣지 못했다")),
            "cards": g["cards"], "held": held, "lost": lost}


