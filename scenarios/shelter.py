def _revealed_cards_text(ids: list) -> str:
    ls = []
    for cid in ids:
        c = get_card(cid)
        if c:
            where = f'{c["locName"]} · {c["spot"]}' if c.get("spot") else c["locName"]
            ls.append(f'[{where}] {c["title"]}: {c["text"]}')
    return "\n".join(ls) or "(아직 아무것도 공개되지 않았다.)"


def _table_text(table: list) -> str:
    def line(t: dict) -> str:
        who = t.get("speaker") or t.get("name") or "?"
        # 알리바이는 사건 직후 한 바퀴 돌린 진술이다. 방금 한 말과 섞어놓으면
        # 배역이 그것을 지금 오간 대화로 착각하고 되받아친다.
        if t.get("kind") == "alibi":
            return f'{who}(사건 직후 알리바이 진술 · {t.get("at","")}): {t.get("text","")}'
        return f'{who}: {t.get("text","")}'

    return "\n".join(line(t) for t in table[-14:]) or "(아직 아무도 말하지 않았다.)"


def _dossier_text(c: dict) -> str:
    parts = [f"● 한 줄 정체\n{c.get('hook','')}"]
    if c.get("storyPast"):
        parts.append(f"● 내가 여기 오기까지\n{c['storyPast']}")
    if c.get("storyToday"):
        parts.append(f"● 어젯밤, 내가 한 일\n{c['storyToday']}")
    if c.get("hide"):
        parts.append("● 들키면 위험한 사실\n" + "\n".join(f"- {x}" for x in c["hide"]))
    if c.get("sins"):
        parts.append("● 내가 실제로 한 짓\n" + "\n".join(f"- {x}" for x in c["sins"]))
    return "\n\n".join(parts)


def _hand_cards_text(hand_ids: list, role_id: str = "") -> str:
    """손패를 그 배역 입장에서 「무기냐 폭탄이냐」까지 붙여 넘긴다."""
    if not hand_ids:
        return "(아직 네가 손에 쥔 것은 없다.)"
    keep = set((KEEP_GOALS.get(role_id) or {}).get("cards", []))
    hide = set(((INVEST_AI.get(role_id) or {}).get("hide")) or [])
    lines = []
    for cid in hand_ids:
        c = get_card(cid)
        if not c:
            continue
        where = f'{c["locName"]} · {c["spot"]}' if c.get("spot") else c["locName"]
        at = CARD_POINTS_AT.get(cid, [])
        if cid in keep:
            tag = "【절대 안 됨】 끝까지 네 손에 있어야 점수가 된다. 있다는 것조차 알리지 마라."
        elif cid in hide or role_id in at:
            tag = "【폭탄 · 나를 가리킨다】 이게 나오면 네가 몰린다. 없는 척하거나 다르게 말해라 — 거짓말해도 된다."
        elif at:
            who = ", ".join((get_character(r) or {}).get("name", r) for r in at)
            tag = f"【무기 · {who}을(를) 가리킨다】 먼저 꺼내 들이대라."
        else:
            tag = "【중립】 감출 이유가 없다. 필요하면 근거로 써라."
        lines.append(f'[{where}] {c["title"]}: {c["text"]}\n  → {tag}')
    return "\n".join(lines)


def _suspicion_text(me: str, seq: int) -> str:
    """다른 셋을 어떤 각도로 보게 되는가. 자기 것은 빼고 준다 —
    본인이 자기 동기를 읊으면 그건 자백이지 의심이 아니다.
    1차 토론까지는 아직 서로를 이렇게 못 본다. 2차부터 열린다."""
    if seq < 5:
        return "아직 서로를 의심할 만한 것이 안 나왔다. 지금은 무슨 일이 있었는지부터 맞춰봐라."
    out = []
    for c in CHARACTERS:
        if c["id"] == me:
            continue
        lines = SUSPICION.get(c["id"]) or []
        if lines:
            out.append(f'· {c["name"]} — ' + " / ".join(lines))
    return "\n".join(out) or "—"


