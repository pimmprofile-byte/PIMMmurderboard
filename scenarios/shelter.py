def decision_report(picks: dict, extra: str = "none", barred: str = "") -> dict:
    """네 칸을 채운 결과를 읽는다.
    picks 는 {roleId: optionId}. barred 는 결재권을 잃은 사람(범인으로 지목된 사람)이고,
    그 칸은 남은 사람들이 투표로 채운 값이 그대로 picks 에 들어온다."""
    go = sum(1 for seat in DECISION[:3]
             if next((o for o in seat["options"] if o["id"] == picks.get(seat["roleId"])), {}).get("lean") == "go")
    lean = "go" if go >= 2 else "stop"
    final = picks.get("riminhui")
    flipped = (final == "against")
    verdict = ("stop" if lean == "go" else "go") if flipped else lean
    lines = []
    for seat in DECISION:
        opt = next((o for o in seat["options"] if o["id"] == picks.get(seat["roleId"])), None)
        if opt:
            lines.append(f'{seat["seat"]} — {opt["line"]}')
    return {"verdict": "성공" if verdict == "go" else "실패",
            "key": verdict, "lean": lean, "flipped": flipped,
            "goCount": go, "lines": lines, "extra": extra, "barred": barred,
            "note": ("전략란이 앞의 세 항과 어긋난다. 받는 쪽은 이것을 내부 이견으로 읽는다."
                     if flipped else "네 항이 한 방향이다. 받는 쪽은 이것을 합의로 읽는다.")}

