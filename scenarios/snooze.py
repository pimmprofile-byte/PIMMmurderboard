def compute_ending(grades: dict):
    """손이 둘이라 채점도 둘이다 — namedAttempt(어제 아침 바질) / namedKiller(오늘 새벽 넬)."""
    ids = [c["id"] for c in CHARACTERS]
    if not all(rid in grades for rid in ids):
        return None
    att = [r for r in ids if grades.get(r, {}).get("namedAttempt")]
    kil = [r for r in ids if grades.get(r, {}).get("namedKiller")]
    if len(att) == len(ids) and len(kil) == len(ids):
        key = "both"
    elif att or kil:
        key = "half"
    else:
        key = "wrong"
    e = ENDINGS[key]
    return {"key": key, "name": e["name"], "tone": e["tone"], "desc": e["desc"],
            "namedAttempt": att, "namedKiller": kil, "truth": TRUTH_FULL}


