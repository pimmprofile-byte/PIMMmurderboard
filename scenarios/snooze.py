def night_truth() -> str:
    """그날 밤 실제로 일어난 일. 진상 원고 뒤에 붙어서 채점과 공개의 기준이 된다."""
    res = _night_result()
    if not res:
        return ""
    order = res.get("order") or []
    ls = ["", "■ 그리고 어젯밤 — 이 판에서 실제로 일어난 일", ""]
    if order:
        for i, x in enumerate(order):
            who = _NIGHT_NAMES.get(x["role"], x["role"])
            ls.append(f"  {x['at']}  {who} — " +
                      ("★ 이 사람이 죽였다." if i == 0 else "이미 식은 몸에 자기 방법을 한 번 더 얹었다."))
    else:
        ls.append("  아무도 그 방에 안 갔다. 마시 선생이 놓고 간 약이 두 번 겹쳐 그는 그냥 식었다.")
    for o in (res.get("skips") or []):
        sk = _NIGHT_SKIP.get(o) or {}
        ls.append(f"  (그 시간에) {_NIGHT_NAMES.get(sk.get('who'), '')} — {sk.get('public','').lstrip('…')}")
    ls.append("")
    ls.append(f"  → 「오늘 새벽의 손」은 {_killer_name()} 이다.")
    return "\n".join(ls)


