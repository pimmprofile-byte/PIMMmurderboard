def _vn_lines(text: str) -> list:
    """독백 한 덩이를 컷 대사 두 줄로. 한 줄짜리면 한 줄로 둔다 —
    앞뒤를 같이 집으면 같은 문장이 두 번 뜬다."""
    ls = [x for x in str(text).split("\n") if x.strip()]
    return ls[:2] if len(ls) > 1 else ls


