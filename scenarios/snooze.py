    """끝까지 손에 쥐고 있어야 점수가 된다 — 공개했거나 버렸으면 0이다."""
    kg = KEEP_GOALS.get(role_id)
    if not kg:
        return None
    ok = all(cid in hand for cid in kg["cards"])
    return {"roleId": role_id, "label": kg["label"], "points": kg["points"] if ok else 0,
            "ok": ok, "fail": "" if ok else kg["fail"]}


