# 그날 밤 각자가 무엇을 했는지에 따라 집에 남는 자국이 다르다.
# 여섯 장을 재워뒀다가 해당하는 셋만 3라운드로 깨운다.
_NIGHT_TRACE = {
    "kieran": {"go": "D3", "skip": "D4"},
    "nell":   {"go": "G2", "skip": "H2"},
    "basil":  {"go": "E4", "skip": "E5"},
}
_TRACE_IDS = {c for t in _NIGHT_TRACE.values() for c in t.values()}


def _sync_night_cards() -> None:
    res = ((_ROOM_STATE.get("night") or {}).get("result")) or {}
    want = set()
    if res:
        went = {x["role"] for x in (res.get("order") or [])}
        for rid, t in _NIGHT_TRACE.items():
            want.add(t["go"] if rid in went else t["skip"])
    for c in CARDS:
        if c["id"] in _TRACE_IDS:
            c["round"] = 3 if c["id"] in want else 9


def set_room_state(st: dict) -> None:
    _ROOM_STATE.update(st or {})
    _sync_night_cards()


def _night_result() -> dict:
    return ((_ROOM_STATE.get("night") or {}).get("result")) or {}


